namespace Hlechyky.Games.Impl;

/// <summary>
/// Плитка конкурсу в лобі — і, на жаль, єдиний спосіб донести до браузера файл
/// <c>web/games/ad-contest.js</c>.
///
/// Сам конкурс — не гра-кімната: правила, записи й голоси живуть у <see cref="AdContest"/> і ходять
/// власним HTTP. Але завантажувач модулів у <c>core.js</c> бере список файлів рівно з каталогу ігор
/// (<c>catalog.games.map(moduleOf)</c>), тож модуль, який реєструє лише панель через
/// <c>HGames.registerPanel</c>, не завантажився б ніколи: у каталозі його нема, а дописувати
/// <c>index.html</c> чи <c>core.js</c> цьому пакету не можна. Звідси цей паспорт: він кладе
/// <c>ad-contest</c> в каталог, браузер тягне модуль — і модуль реєструє і панель «🎙 Реклама»,
/// і цю картку, малюючи в обох одне й те саме.
///
/// Стану в грі нема взагалі: вид порожній, ходів нема, партія просто стоїть відкритою, поки людина не
/// закриє картку. Кімната приватна й соло, тож у лобі вона не висить і нікому не заважає.
/// Якщо каркас колись навчиться вантажити модулі панелей сам — цей клас треба прибрати першим.
/// </summary>
public sealed class AdContestTile : Game
{
    public override GameInfo Info { get; } = new(
        "ad-contest", "Реклама глека", "рекламу глека", GameGroup.Party, 1, 1,
        Start: StartMode.Immediate, Private: true,
        Hint: "Конкурс: озвуч рекламу глека, послухай чужі й віддай голос. Переможна реклама йде в ефір.");

    public override void Start() { }

    /// <summary>Уся правда про конкурс приходить окремо, через <c>GET /api/ads</c>.</summary>
    public override object View(int? seat) => new { };
}
