namespace Hlechyky.Games.Impl;

/// <summary>
/// Ставок «Ковзанки»: одна ручна мапа 30×20 клітинок по 32 одиниці (світ 960×640, як ярмарок Юрми — клієнтові
/// так само зручно ділити екран). Лід — лише <c>.</c>; решта — сніг берега, очерет, острівець, вмерзлий човен.
/// Ласощі, що їх розкидають по льоду, й імена селян — теж тут. Усе стале, рахується раз на процес.
/// </summary>
public static class SkateMap
{
    public const int W = 30, H = 20, Cell = 32, Cells = W * H;
    public const int WorldW = W * Cell, WorldH = H * Cell;

    /// <summary>
    /// Легенда: <c>.</c> лід (єдине, де можна бути), <c>#</c> сніговий берег, <c>R</c> очерет, <c>T</c> ялина, <c>H</c> хата,
    /// <c>B</c> лавка з вогнищем, <c>I</c> острівець із вербою, <c>K</c> вмерзлий човен. Перевірено тестом: 400 клітинок
    /// льоду, усі з'єднані.
    /// </summary>
    public static readonly string[] Rows =
    [
        "##############################",
        "##TT####HH#####BB###HH####TT##",
        "####RR...................RR###",
        "###R.......................R##",
        "##R.........................##",
        "##...........................#",
        "#R...........................#",
        "#............................#",
        "#.........II.................#",
        "#........IIII................#",
        "#.........II.................#",
        "#............................#",
        "#....................KK......#",
        "#R...........................#",
        "##...........................#",
        "##R.........................##",
        "###R.......................R##",
        "####RR...................RR###",
        "##TT####HH#####TT###HH####TT##",
        "##############################",
    ];

    /// <summary>Ласощі на льоду: назва, «що підхопили» (для «Хтось підхопив бублик»), емодзі. Порядок — номер виду.</summary>
    public static readonly (string Name, string What, string Emoji)[] Kinds =
    [
        ("Бублик", "бублик", "🥯"),
        ("Пряник", "пряник", "🍪"),
        ("Калач", "калач", "🥨"),
        ("Півник", "півника на паличці", "🍭"),
        ("Яблуко", "яблуко в карамелі", "🍎"),
        ("Горіхи", "жменю горіхів", "🌰"),
    ];

    /// <summary>Імена селян: тасуються на кожен раунд, беруться перші N. Ім'я гравця — таке саме, як у бота.</summary>
    public static readonly string[] Names =
    [
        "Параска", "Микола", "Ганна", "Степан", "Одарка", "Тарас", "Марічка", "Гриць",
        "Оксана", "Панас", "Домаха", "Іванко", "Соломія", "Назар", "Мотря", "Богдан",
        "Ярина", "Остап", "Христя", "Данило", "Марта", "Максим", "Устя", "Юрко",
        "Килина", "Левко", "Наталка", "Роман", "Пріська", "Андрійко", "Гафія", "Василь",
        "Софійка", "Тиміш", "Орися", "Прокіп", "Настя", "Лесь", "Явдоха", "Захар",
        "Меланка", "Матвій", "Феся", "Сашко", "Текля", "Ігнат", "Зоряна", "Йосип",
        "Уляна", "Федь", "Люба", "Влас", "Дарина", "Кузьма", "Олеся", "Сидір",
        "Марійка", "Петрик", "Ганнуся", "Демко", "Варка", "Славко", "Катря", "Михась",
    ];

    /// <summary>Лід за індексом клітинки <c>y * W + x</c>.</summary>
    public static readonly bool[] Pass = new bool[Cells];
    /// <summary>Усі клітинки льоду за зростанням індексу.</summary>
    public static readonly int[] Ice;

    static SkateMap()
    {
        var ice = new List<int>();
        for (var y = 0; y < H; y++)
            for (var x = 0; x < W; x++)
            {
                var i = y * W + x;
                Pass[i] = Rows[y][x] == '.';
                if (Pass[i]) ice.Add(i);
            }
        Ice = [.. ice];
    }

    public static int CenterX(int cell) => cell % W * Cell + Cell / 2;
    public static int CenterY(int cell) => cell / W * Cell + Cell / 2;

    /// <summary>Чи лід у точці світу (одиниці); усе поза мапою — ні.</summary>
    public static bool IceAt(int x, int y) => x >= 0 && y >= 0 && x < WorldW && y < WorldH && Pass[y / Cell * W + x / Cell];

    /// <summary>
    /// Чи вміщається коробка з центром (x, y) і половиною <paramref name="half"/> на льоду: чотири кути (x − half … x + half − 1)
    /// — у клітинках льоду. Коробка менша за клітинку, тож кутів досить.
    /// </summary>
    public static bool BoxFits(int x, int y, int half) =>
        IceAt(x - half, y - half) && IceAt(x + half - 1, y - half) && IceAt(x - half, y + half - 1) && IceAt(x + half - 1, y + half - 1);

    /// <summary>Чи лежить увесь квадрат навколо кола (x, y, r) на льоду — так ставимо ополонки: вода не лізе на берег.</summary>
    public static bool DiskOnIce(int x, int y, int r)
    {
        if (x - r < 0 || y - r < 0 || x + r >= WorldW || y + r >= WorldH) return false;
        for (var cy = (y - r) / Cell; cy <= (y + r) / Cell; cy++)
            for (var cx = (x - r) / Cell; cx <= (x + r) / Cell; cx++)
                if (!Pass[cy * W + cx]) return false;
        return true;
    }

    /// <summary>Чи видно з (x0, y0) у (x1, y1) по льоду: точки відрізка кожні 8 одиниць — на льоду. Щоб бот не цілився крізь острів.</summary>
    public static bool Clear(int x0, int y0, int x1, int y1)
    {
        int dx = x1 - x0, dy = y1 - y0;
        var steps = Math.Max(Math.Abs(dx), Math.Abs(dy)) / 8 + 1;
        for (var i = 0; i <= steps; i++)
            if (!IceAt(x0 + dx * i / steps, y0 + dy * i / steps)) return false;
        return true;
    }
}
