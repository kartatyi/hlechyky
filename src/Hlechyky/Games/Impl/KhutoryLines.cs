/// <list type="bullet">
/// <item>Завжди: Start, Win, Longest, LongestLost, Army, Away, Back, SevenAgain і ПЕРША за партію Seven — їх мало
///   (нагороди міняються кілька разів за партію), і це головні новини столу.</item>
/// <item>Решта — не частіше ніж раз на <see cref="Cooldown"/> (25 с від будь-якої попередньої репліки Глека) і не
///   більше одного рядка на хід гравця (ходи відмічає <see cref="NewTurn"/>; рядок «завжди» теж займає хід).
///   Так на 150 ходів виходить ≲ 40 «звичайних» рядків, а в середньому ~1 на 2–3 ходи.</item>
/// <item>Часті дрібниці грають у кості: Harvest/PlayerTrade/Knight — 40 %, BankTrade — 25 % (обмін із банком
///   буває щоходу, тож «зрідка»).</item>
/// <item>NearWin — не більше разу на кожного гравця за партію (інакше дзвонить щоходу, поки лідер не добере очко).</item>
/// <item>Та сама репліка того самого моменту двічі поспіль не звучить.</item>
/// </list>
/// Start починає нову партію (скидає лічильники); <see cref="Reset"/> — те саме вручну.
/// </summary>
public sealed class KhutoryGlek
{
    public static readonly TimeSpan Cooldown = TimeSpan.FromSeconds(25);
    public const double ChanceCommon = 0.40;
    public const double ChanceBankTrade = 0.25;

    readonly Dictionary<KhMoment, int> _last = new();
    readonly HashSet<string> _nearWinSaid = new();
    DateTimeOffset? _lastAt;
    bool _saidThisTurn;
    bool _sevenSaid;

    /// <summary>Новий хід гравця — знову можна один «звичайний» рядок.</summary>
    public void NewTurn() => _saidThisTurn = false;

    /// <summary>Нова партія: забути лічильники (останні репліки пам'ятаємо — щоб і «Ще раз» не почався тим самим).</summary>
    public void Reset()
    {
        _nearWinSaid.Clear();
        _lastAt = null;
        _saidThisTurn = false;
        _sevenSaid = false;
    }

    static bool IsAlways(KhMoment m) => m is KhMoment.Win or KhMoment.Start or KhMoment.Longest
        or KhMoment.LongestLost or KhMoment.Army or KhMoment.Away or KhMoment.Back or KhMoment.SevenAgain;

    /// <summary>Репліка Глека на момент або null, якщо зараз краще помовчати.</summary>
    public string? Say(KhMoment m, DateTimeOffset now, Random rng, IReadOnlyDictionary<string, string>? vars = null)
    {
        if (m == KhMoment.Start) Reset();

        var always = IsAlways(m) || (m == KhMoment.Seven && !_sevenSaid);
        if (!always)
        {
            if (_saidThisTurn) return null;
            if (_lastAt is { } at && now - at < Cooldown) return null;
            if (m == KhMoment.NearWin && vars != null && vars.TryGetValue("who", out var w) && _nearWinSaid.Contains(w))
                return null;
            var chance = m switch
            {
                KhMoment.Harvest or KhMoment.PlayerTrade or KhMoment.Knight => ChanceCommon,
                KhMoment.BankTrade => ChanceBankTrade,
                _ => 1.0,
            };
            if (chance < 1.0 && rng.NextDouble() >= chance) return null;
        }

        if (m == KhMoment.Seven) _sevenSaid = true;
        if (m == KhMoment.NearWin && vars != null && vars.TryGetValue("who", out var who)) _nearWinSaid.Add(who);

        var i = KhutoryLines.PickIndex(m, rng, _last.TryGetValue(m, out var prev) ? prev : -1);
        _last[m] = i;
        _lastAt = now;
        _saidThisTurn = true;
        return KhutoryLines.Fill(KhutoryLines.Lines(m)[i], vars);
    }
}
