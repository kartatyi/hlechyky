    /// <summary>Репліка з пулу. Випадковість — лише з генератора кімнати, інакше партія не відтвориться.</summary>
    public static string Pick(Random rng, string[] pool, params object[] args)
    {
        var line = pool[rng.Next(pool.Length)];
        return args.Length == 0 ? line : string.Format(System.Globalization.CultureInfo.InvariantCulture, line, args);
    }

    /// <summary>«1 очко», «3 очки», «5 очок», «11 очок», «21 очко».</summary>
    public static string Points(long n)
    {
        var a = Math.Abs(n) % 100;
        var word = a is >= 11 and <= 14 ? "очок" : (a % 10) switch { 1 => "очко", 2 or 3 or 4 => "очки", _ => "очок" };
        return $"{n} {word}";
    }

    /// <summary>«Оля», «Оля й Петро», «Оля, Петро й Ганна».</summary>
    public static string Names(IReadOnlyList<string> names) => names.Count switch
    {
        0 => "",
        1 => names[0],
        _ => string.Join(", ", names.Take(names.Count - 1)) + " й " + names[^1],
    };
