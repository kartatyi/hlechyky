/** Крамниця за id: { id, tier, bonus, pts, k, cost: { linen, fish, herbs, clay, wool } }. */
export function card(id) {
  const d = DECK[id];
  if (!d) return null;
  const cost = {};
  GOODS.forEach((g, i) => { cost[g] = d[5][i]; });
  return { id, tier: d[1], bonus: d[2], pts: d[3], k: d[4], cost, name: CARD_NAME[id] };
}

/** Відбиток колоди (FNV-1a 32 над «id:tier:bonus:pts:k:c0,c1,c2,c3,c4», карти через «;»). Сервер рахує те саме. */
export const DECK_SIG = 'f97ba6b0';
export function deckSig(deck = DECK) {
  const s = deck.map((d) => `${d[0]}:${d[1]}:${d[2]}:${d[3]}:${d[4]}:${d[5].join(',')}`).join(';');
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}

