/** Відбиток мапи й замовлень (FNV-1a 32): сервер рахує те саме над тим самим ASCII-рядком (§4.2). */
export const MAP_SIG = '01c5d1de';
export function mapSig() {
  const s = ROUTES.map((r) => `r${r[0]}:${r[1]}:${r[2]}:${r[3]}:${r[4]}:${r[5] === null ? '' : r[5]}`).join(';')
    + '|' + TICKETS.map((t) => `t${t[0]}:${t[1]}:${t[2]}:${t[4]}`).join(';');
  let h = 0x811c9dc5;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 0x01000193) >>> 0; }
  return h.toString(16).padStart(8, '0');
}

/** Геометрія слотів (§4.3), однакова в 3D і 2D. Парні шляхи — дві смуги на ±LANE від спільної кривої. */
export const LANE = 22, SLOT_W = 28, SLOT_GAP = 10, CURVE_SEGS = 64;
/** Лінія шляху в одиницях мапи: { pts: [[x, y] × (CURVE_SEGS + 1)], arc: [довжина до точки], total }. */
export function routeCurve(id) {
  const r = route(id), A = city(r.a), B = city(r.b);
  const dx = B.x - A.x, dy = B.y - A.y, d = Math.hypot(dx, dy), nx = -dy / d, ny = dx / d;
  const cx = (A.x + B.x) / 2 + nx * 2 * r.bend, cy = (A.y + B.y) / 2 + ny * 2 * r.bend;   // середина кривої зсунута на bend
  const off = r.twin === null ? 0 : (id < r.twin ? LANE : -LANE);
  const pts = [], arc = [];
  let total = 0;
  for (let i = 0; i <= CURVE_SEGS; i++) {
    const t = i / CURVE_SEGS, u = 1 - t;
    const x = u * u * A.x + 2 * u * t * cx + t * t * B.x, y = u * u * A.y + 2 * u * t * cy + t * t * B.y;
    const tx = 2 * u * (cx - A.x) + 2 * t * (B.x - cx), ty = 2 * u * (cy - A.y) + 2 * t * (B.y - cy), tl = Math.hypot(tx, ty);
    const p = [x - (ty / tl) * off, y + (tx / tl) * off];
    if (i) total += Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]);
    pts.push(p); arc.push(total);
  }
  return { pts, arc, total };
}
/** Слоти шляху від a до b: [{ x, y, a (кут, рад), len, w }] — рівно route(id).len штук, рівні проміжки, відступ r міст з обох кінців. */
export function routeSlots(id) {
  const r = route(id), C = routeCurve(id), r0 = city(r.a).r, cell = (C.total - r0 - city(r.b).r) / r.len, out = [];
  const at = (s) => {
    let i = 1;
    while (i < CURVE_SEGS && C.arc[i] < s) i++;
    const k = (s - C.arc[i - 1]) / (C.arc[i] - C.arc[i - 1] || 1), P = C.pts[i - 1], Q = C.pts[i];
    return { x: P[0] + (Q[0] - P[0]) * k, y: P[1] + (Q[1] - P[1]) * k, a: Math.atan2(Q[1] - P[1], Q[0] - P[0]) };
  };
  for (let n = 0; n < r.len; n++) out.push({ ...at(r0 + (n + 0.5) * cell), len: cell - SLOT_GAP, w: SLOT_W });
  return out;
}

