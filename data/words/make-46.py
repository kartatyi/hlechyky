def main():
    db = sqlite3.connect("file:uk-all.db?mode=ro", uri=True)
    known = lambda w: db.execute("SELECT 1 FROM words WHERE w=?", (w,)).fetchone() is not None
    hang = [l.strip() for l in open("uk-hangman.txt", encoding="utf-8") if l.strip()]
    lists = {
        4: {w for w in FOUR if len(w) == 4},
        6: {w for w in hang if len(w) == 6 and w not in DROP6},
    }
    for n, words in lists.items():
        bad = sorted(w for w in words if not all(ch in UA for ch in w) or not known(w))
        if bad:
            print(f"uk-{n}: нема в uk-all.db, викинуто:", " ".join(bad))
        good = sorted(words - set(bad))
        with open(f"uk-{n}.txt", "w", encoding="utf-8", newline="\n") as f:
            for w in good:
                f.write(w + "\n")
        print(f"uk-{n}.txt", len(good))
    short = sorted(w for w in FOUR if len(w) != 4)
    if short:
        print("не чотири літери:", " ".join(short))


if __name__ == "__main__":
    main()
